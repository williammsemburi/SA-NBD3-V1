injury_reconstruct_nims_national_counts <- function(expanded_counts) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(expanded_counts))
  fine_key <- c("Death_Prov", "Sex", "Popgroup", "age5", "nbdcode")
  assert_has_columns(
    x,
    c(fine_key, "Inj2000", "EffN2000", "nims_source_zero"),
    "expanded NIMS count panel"
  )
  assert_unique_key(x, fine_key, "expanded NIMS count panel")
  for (column in c("Inj2000", "EffN2000")) {
    x[, (column) := suppressWarnings(as.numeric(get(column)))]
    if (x[!is.finite(get(column)) | get(column) < 0, .N]) {
      stop("Expanded NIMS counts contain invalid values in ", column, ".",
           call. = FALSE)
    }
  }
  x[, nims_source_zero := as.logical(nims_source_zero)]
  x[is.na(nims_source_zero), nims_source_zero := TRUE]

  national_counts <- x[, .(
    Inj2000 = sum(Inj2000, na.rm = TRUE),
    nims_source_zero = all(nims_source_zero)
  ), by = .(Sex, age5, nbdcode)]

  # EffN2000 is repeated across causes after the national NIMS information size
  # is allocated over province-population-group strata. Sum one value per fine
  # stratum to reconstruct the original sex-age information size.
  fine_effective <- unique(x[, .(
    Death_Prov, Popgroup, Sex, age5, EffN2000
  )])
  assert_unique_key(
    fine_effective,
    c("Death_Prov", "Popgroup", "Sex", "age5"),
    "expanded NIMS fine-stratum effective sizes"
  )
  national_effective <- fine_effective[, .(
    EffN2000 = sum(EffN2000, na.rm = TRUE)
  ), by = .(Sex, age5)]

  out <- merge(
    national_counts,
    national_effective,
    by = c("Sex", "age5"),
    all.x = TRUE,
    sort = FALSE
  )
  out[!is.finite(EffN2000) | EffN2000 < 0, EffN2000 := 0]
  data.table::setorder(out, Sex, age5, nbdcode)
  assert_unique_key(out, c("Sex", "age5", "nbdcode"),
                    "reconstructed national NIMS counts")
  out[]
}

injury_draw_nims_count_panel <- function(
    counts,
    seed,
    fraction_floor = 1e-8) {
  require_package("data.table")
  if (length(seed) != 1L || !is.finite(as.numeric(seed))) {
    stop("A finite NIMS composition seed is required.", call. = FALSE)
  }
  fraction_floor <- suppressWarnings(as.numeric(fraction_floor))
  if (length(fraction_floor) != 1L || !is.finite(fraction_floor) ||
      fraction_floor <= 0) {
    stop("A positive NIMS fraction floor is required.", call. = FALSE)
  }

  x <- data.table::as.data.table(data.table::copy(counts))
  key <- c("Death_Prov", "Sex", "Popgroup", "age5", "nbdcode")
  assert_has_columns(
    x,
    c(
      key, "Inj2000", "EffN2000", "nims_source_zero",
      "Inj2009", "Inj2017", "EffN2009", "EffN2017"
    ),
    "combined injury survey count draw"
  )
  assert_unique_key(x, key, "combined injury survey count draw")

  set.seed(as.integer(seed))
  national <- injury_reconstruct_nims_national_counts(x)
  national[, Inj2000 := {
    total <- sum(Inj2000, na.rm = TRUE)
    if (!is.finite(total) || total <= 0) {
      rep(0, .N)
    } else {
      effective_n <- unique(EffN2000)
      if (length(effective_n) != 1L) {
        stop("NIMS effective size is not unique within sex-age.", call. = FALSE)
      }
      drawn_fraction <- injury_draw_dirichlet_profile(
        Inj2000 / total,
        effective_n = effective_n,
        alpha_floor = max(fraction_floor, .Machine$double.eps)
      )
      total * drawn_fraction
    }
  }, by = .(Sex, age5)]

  # NIMS is national. Its province-population-group expansion is informed by
  # the same IMS PSU-bootstrap replicate used for the 2009 level/profile and
  # cause counts. This preserves the intended NIMS-IMS dependence.
  expanded_nims <- expand_nims_2000_with_ims(
    national,
    x[, .(Death_Prov, Sex, Popgroup, age5, nbdcode, Inj2009)]
  )
  other <- x[, .(
    Death_Prov, Sex, Popgroup, age5, nbdcode,
    Inj2009, Inj2017, EffN2009, EffN2017
  )]
  out <- merge(
    expanded_nims,
    other,
    by = key,
    all.x = TRUE,
    sort = FALSE
  )
  for (column in c("Inj2009", "Inj2017", "EffN2009", "EffN2017")) {
    out[is.na(get(column)), (column) := 0]
  }
  data.table::setorderv(out, key)
  assert_unique_key(out, key, "drawn NIMS-IMS-FAMHIS count panel")
  out[]
}

injury_draw_fraction_panel <- function(artifact, seed, survey_counts = NULL) {
  if (is.null(survey_counts)) {
    drawn_surveys <- injury_draw_survey_compositions(
      artifact$source_fractions,
      seed = seed
    )
    return(injury_compose_fraction_panel(artifact, drawn_surveys))
  }

  counts <- injury_merge_survey_design_draw(artifact, survey_counts)

  # Draw the national NIMS sex-age composition from its count information
  # BEFORE expanding it with the sampled IMS profile and BEFORE harmonising
  # causes 132, 136 and 138. Applying the cross-survey correction first makes
  # fine cells that share a raw NIMS donor legitimately different and therefore
  # cannot be represented by one common borrowed-composition draw.
  counts <- injury_draw_nims_count_panel(
    counts,
    seed = seed,
    fraction_floor = artifact$parameters$fraction_floor
  )
  observed <- survey_counts_to_fractions(
    counts,
    nims_year = artifact$parameters$nims_year,
    ims_year = artifact$parameters$ims_year,
    famhis_year = artifact$parameters$famhis_year,
    fraction_floor = artifact$parameters$fraction_floor,
    bias_floor = artifact$parameters$bias_floor,
    reference_code = artifact$parameters$reference_code
  )

  # IMS and FAMHIS are already sampled by the joint PSU bootstrap and NIMS has
  # now been sampled from its national count information. The harmonised survey
  # anchors can therefore be passed directly to the deterministic ALR path.
  injury_compose_fraction_panel(artifact, observed)
}

