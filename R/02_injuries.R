# Injury-envelope level and relative-profile calibration ----------------------
#
# IMS 2009 and FAMHIS 2017 are weighted national injury-mortality surveys.
# They inform two distinct quantities:
#
#   1. the national total number of injury deaths (the level); and
#   2. the relative province-sex-age distribution of those deaths (the profile).
#
# The former share-based implementation compared the proportion of survey
# records classified as non-natural with the injury share of the completed
# all-cause mortality envelope. Those denominators are not comparable because
# the surveys were sampled through forensic mortuaries. It could therefore
# convert most mortality into injuries and, by subtraction, collapse the
# natural-cause and HIV/AIDS estimates.
#
# The corrected model uses the survey weights in the way the injury surveys were
# designed to be used: weighted injury totals estimate the national injury
# level, while normalised weighted totals estimate the relative profile.
#
# At each survey year y:
#
#   level_ratio_y = weighted survey injury total_y /
#                   completed routine injury total_y
#
# and, over province x sex x age cells g:
#
#   profile_scalar_gy = survey_share_gy / routine_share_gy.
#
# Both are interpolated on the log scale. When the adjustment is applied, one
# annual log-odds intercept is solved so that the adjusted national injury total
# equals the survey-calibrated target, while every province-sex-year-
# population-group-age all-cause cell is preserved. Thus injury and natural
# deaths remain positive complements within the already completed all-cause
# envelope.

injury_envelope_model_parameters <- function(cfg) {
  start_year <- as.integer(cfg$settings$start_year)
  end_year <- as.integer(cfg$settings$end_year)
  ims_year <- as.integer(cfg$settings$injury_ims_year %||% 2009L)
  famhis_year <- as.integer(cfg$settings$injury_famhis_year %||% 2017L)
  smoothing_window <- as.integer(
    cfg$settings$injury_envelope_age_smoothing_window %||% 5L
  )
  profile_floor <- as.numeric(
    cfg$settings$injury_envelope_profile_floor %||% 1e-10
  )
  dirichlet_alpha_floor <- as.numeric(
    cfg$settings$injury_envelope_alpha_floor %||% 1e-8
  )
  method <- as.character(
    cfg$settings$injury_envelope_method %||%
      "ims2009_famhis2017_level_plus_relative_profile"
  )
  allowed <- c(
    "ims2009_famhis2017_level_plus_relative_profile",
    "ims2009_famhis2017_empirical_level_plus_relative_profile",
    # Compatibility aliases from the development sequence. They are mapped to
    # the executed level-plus-profile method so an existing config can run.
    "ims2009_famhis2017_relative_odds_triangular_age_smoother",
    "ims2009_famhis2017_log_ratio_triangular_age_smoother",
    "ims2009_famhis2017_relative_profile_odds_calibration"
  )
  if (!method %in% allowed) {
    stop(
      "Unsupported injury_envelope_method: ", method,
      ". Expected ims2009_famhis2017_level_plus_relative_profile.",
      call. = FALSE
    )
  }
  method <- "ims2009_famhis2017_level_plus_relative_profile"

  # The deterministic national injury-level anchors are estimated from the
  # corrected IMS and FAMHIS weights in prepare_*_envelope(). The optional
  # values below are external reference estimates and confidence intervals used
  # only for audit; they never replace the survey-derived point estimate or
  # determine its survey-design uncertainty.
  level_reference <- list(
    `2009` = list(
      estimate = suppressWarnings(as.numeric(
        cfg$settings$injury_ims_level_estimate %||% NA_real_
      )),
      lower = suppressWarnings(as.numeric(
        cfg$settings$injury_ims_level_lower %||% NA_real_
      )),
      upper = suppressWarnings(as.numeric(
        cfg$settings$injury_ims_level_upper %||% NA_real_
      )),
      source = as.character(
        cfg$settings$injury_ims_level_source %||%
          "No external IMS level reference configured"
      )
    ),
    `2017` = list(
      estimate = suppressWarnings(as.numeric(
        cfg$settings$injury_famhis_level_estimate %||% NA_real_
      )),
      lower = suppressWarnings(as.numeric(
        cfg$settings$injury_famhis_level_lower %||% NA_real_
      )),
      upper = suppressWarnings(as.numeric(
        cfg$settings$injury_famhis_level_upper %||% NA_real_
      )),
      source = as.character(
        cfg$settings$injury_famhis_level_source %||%
          "No external FAMHIS level reference configured"
      )
    )
  )
  for (year_key in names(level_reference)) {
    item <- level_reference[[year_key]]
    values <- c(item$estimate, item$lower, item$upper)
    supplied <- is.finite(values)
    if (any(supplied) && !all(supplied)) {
      stop(
        "The external injury-level reference for ", year_key,
        " must supply estimate, lower, and upper together.",
        call. = FALSE
      )
    }
    if (all(supplied) &&
        (item$estimate <= 0 || item$lower <= 0 ||
         item$upper <= item$lower || item$estimate < item$lower ||
         item$estimate > item$upper)) {
      stop(
        "The external injury-level reference is invalid for ", year_key,
        ".",
        call. = FALSE
      )
    }
  }

  if (any(!is.finite(c(start_year, end_year, ims_year, famhis_year))) ||
      start_year > ims_year || ims_year >= famhis_year || famhis_year > end_year) {
    stop("The injury-envelope survey years are incompatible with the analysis period.",
         call. = FALSE)
  }
  if (!is.finite(profile_floor) || profile_floor <= 0 || profile_floor >= 0.01) {
    stop("injury_envelope_profile_floor must be between zero and 0.01.",
         call. = FALSE)
  }
  if (!is.finite(dirichlet_alpha_floor) || dirichlet_alpha_floor <= 0) {
    stop("injury_envelope_alpha_floor must be finite and positive.",
         call. = FALSE)
  }
  ages <- 1:20
  list(
    method = method,
    years = seq.int(start_year, end_year),
    ages = ages,
    anchor_years = c(ims_year, famhis_year),
    smoothing_window = smoothing_window,
    age_smoothing_matrix = injury_smoothing_matrix(
      ages,
      window = smoothing_window
    ),
    profile_floor = profile_floor,
    dirichlet_alpha_floor = dirichlet_alpha_floor,
    level_reference = level_reference,
    profile_scope = "national province-sex-age injury distribution",
    level_scope = "national injury total among calibration-active ages",
    calibration_scope = "national year",
    eligible_envelope = paste(
      "injury plus natural deaths within each",
      "province-sex-year-population-group-age cell"
    ),
    pre_2009_policy = "Hold the IMS 2009 level and profile through 2009",
    between_policy = paste(
      "Interpolate the log national level ratio and the log relative profile",
      "between 2009 and 2017"
    ),
    post_2017_policy = "Hold the FAMHIS 2017 level and profile through 2019"
  )
}

injury_normalise_profile <- function(values, floor = 1e-10) {
  x <- suppressWarnings(as.numeric(values))
  x[!is.finite(x) | x < 0] <- 0
  if (!length(x)) return(numeric())
  if (sum(x) <= 0) return(rep(1 / length(x), length(x)))
  p <- x / sum(x)
  p <- pmax(p, floor)
  p / sum(p)
}

injury_safe_exp <- function(log_values) {
  x <- suppressWarnings(as.numeric(log_values))
  lower <- log(.Machine$double.xmin)
  upper <- log(.Machine$double.xmax)
  exp(pmin(pmax(x, lower), upper))
}


injury_envelope_anchor_table <- function(
    baseline,
    envelope_surveys,
    cfg) {
  require_package("data.table")
  parameters <- injury_envelope_model_parameters(cfg)
  cell <- c("Death_Prov", "Sex", "age5")
  anchor_years <- parameters$anchor_years

  x <- data.table::as.data.table(data.table::copy(baseline))
  assert_has_columns(
    x,
    c("Death_Prov", "Sex", "DeathYear", "Popgroup", "age5", "nbdcode", "Deaths"),
    "pre-calibration Stage 04 data"
  )
  routine <- x[
    DeathYear %in% anchor_years,
    .(
      routine_injury_total = sum(
        Deaths[nbdcode %in% INJURY_CODES],
        na.rm = TRUE
      ),
      routine_natural_total = sum(
        Deaths[!nbdcode %in% INJURY_CODES],
        na.rm = TRUE
      )
    ),
    by = .(Death_Prov, Sex, age5, survey_year = DeathYear)
  ]
  routine[, routine_total := routine_injury_total + routine_natural_total]
  routine <- complete_cells(
    routine,
    dimensions = c(cell, "survey_year"),
    values = c(
      "routine_injury_total",
      "routine_natural_total",
      "routine_total"
    ),
    levels = list(
      Death_Prov = 1:9,
      Sex = 1:2,
      age5 = 1:20,
      survey_year = anchor_years
    )
  )

  survey <- data.table::as.data.table(data.table::copy(envelope_surveys))
  assert_has_columns(
    survey,
    c(
      cell, "survey_year", "survey", "survey_total",
      "survey_injury_total", "survey_effective_n",
      "survey_level_estimate", "survey_level_record_total",
      "survey_level_source"
    ),
    "injury-envelope surveys"
  )
  survey[, `:=`(
    Death_Prov = as.integer(Death_Prov),
    Sex = as.integer(Sex),
    age5 = as.integer(age5),
    survey_year = as.integer(survey_year),
    survey_total = as.numeric(survey_total),
    survey_injury_total = as.numeric(survey_injury_total),
    survey_effective_n = as.numeric(survey_effective_n),
    survey_level_estimate = as.numeric(survey_level_estimate),
    survey_level_record_total = as.numeric(survey_level_record_total),
    survey_level_source = as.character(survey_level_source)
  )]
  survey <- survey[survey_year %in% anchor_years]
  assert_unique_key(survey, c(cell, "survey_year"), "injury-envelope surveys")

  base <- merge(
    routine,
    survey,
    by = c(cell, "survey_year"),
    all.x = TRUE,
    sort = FALSE
  )
  base[is.na(survey_injury_total) | !is.finite(survey_injury_total) |
         survey_injury_total < 0,
       survey_injury_total := 0]
  base[is.na(survey_total) | !is.finite(survey_total) | survey_total < 0,
       survey_total := 0]
  base[
    is.na(survey_effective_n) | !is.finite(survey_effective_n) |
      survey_effective_n < 0,
    survey_effective_n := 0
  ]

  # The original IMS scaling program held neonatal and post-neonatal injury
  # completeness at the routine value. Retain that point-estimate rule through
  # 2009; FAMHIS can inform these ages from 2017 onward.
  base[, calibration_active := !(
    survey_year == anchor_years[[1L]] & age5 %in% 1:2
  )]
  data.table::setorder(base, survey_year, Death_Prov, Sex, age5)

  profile <- base[, {
    active <- calibration_active
    routine_active <- routine_injury_total[active]
    survey_active <- survey_injury_total[active]
    effective_active <- survey_effective_n[active]

    # The national level ratio is always defined on the all-age injury total.
    # This makes the survey-year calibration reproduce the empirical weighted
    # survey total calculated from the raw records. External published estimates
    # are validation benchmarks only. Cells excluded from the relative-profile
    # calibration (the historical IMS infant rule) remain fixed, and the
    # adjustable ages absorb the remainder of the national target.
    routine_level_total <- sum(routine_injury_total, na.rm = TRUE)
    routine_adjustable_injury_total <- sum(routine_active, na.rm = TRUE)
    routine_fixed_injury_total <- sum(
      routine_injury_total[!active],
      na.rm = TRUE
    )
    processed_survey_level_total <- sum(survey_active, na.rm = TRUE)
    processed_survey_all_age_total <- sum(
      survey_injury_total,
      na.rm = TRUE
    )
    profile_effective_n <- sum(effective_active, na.rm = TRUE)

    if (!is.finite(routine_level_total) || routine_level_total <= 0 ||
        !is.finite(routine_adjustable_injury_total) ||
        routine_adjustable_injury_total <= 0 ||
        !is.finite(routine_fixed_injury_total) ||
        routine_fixed_injury_total < 0) {
      stop("The routine injury totals at a survey anchor are invalid.",
           call. = FALSE)
    }
    if (!is.finite(processed_survey_level_total) ||
        processed_survey_level_total <= 0 ||
        !is.finite(processed_survey_all_age_total) ||
        processed_survey_all_age_total <= 0) {
      stop("The prepared weighted survey injury total at an anchor is not positive.",
           call. = FALSE)
    }
    if (!is.finite(profile_effective_n) || profile_effective_n <= 0) {
      stop("The injury survey profile has no positive effective information.",
           call. = FALSE)
    }

    year_key <- as.character(survey_year[[1L]])
    derived_level_values <- unique(survey_level_estimate)
    derived_level_values <- derived_level_values[is.finite(derived_level_values)]
    if (length(derived_level_values) != 1L ||
        derived_level_values[[1L]] <= 0) {
      stop(
        "The weighted survey analysis did not produce one positive national ",
        "injury-level estimate for ", year_key, ".",
        call. = FALSE
      )
    }
    derived_survey_level_total <- derived_level_values[[1L]]
    derived_level_source_values <- unique(survey_level_source)
    derived_level_source_values <- derived_level_source_values[
      !is.na(derived_level_source_values) & nzchar(derived_level_source_values)
    ]
    derived_survey_level_source <- if (length(derived_level_source_values)) {
      derived_level_source_values[[1L]]
    } else {
      paste0("Calculated from corrected survey weights for ", year_key)
    }

    level_reference <- parameters$level_reference[[year_key]]
    reference_values <- if (is.null(level_reference)) {
      rep(NA_real_, 3L)
    } else {
      c(level_reference$estimate, level_reference$lower, level_reference$upper)
    }
    reference_available <- all(is.finite(reference_values))
    published_survey_level_total <- if (reference_available) {
      as.numeric(reference_values[[1L]])
    } else {
      NA_real_
    }
    published_survey_level_lower <- if (reference_available) {
      as.numeric(reference_values[[2L]])
    } else {
      NA_real_
    }
    published_survey_level_upper <- if (reference_available) {
      as.numeric(reference_values[[3L]])
    } else {
      NA_real_
    }
    # Published estimates are retained as external validation benchmarks.
    # The reproducible point estimate comes from the supplied microdata,
    # eligibility rule and survey weights, so a difference from a published
    # interval is reported rather than used to replace or reject the empirical
    # result.
    outside_reference_interval <- reference_available &&
      (derived_survey_level_total < published_survey_level_lower ||
       derived_survey_level_total > published_survey_level_upper)

    survey_active_fraction <- processed_survey_level_total /
      processed_survey_all_age_total
    # The deterministic point anchor comes from this run's corrected survey
    # weights, not from a hard-coded external total.
    survey_level_total <- derived_survey_level_total
    target_adjustable_injury_total <-
      survey_level_total - routine_fixed_injury_total
    maximum_adjustable_injury_total <- sum(
      routine_total[active],
      na.rm = TRUE
    )
    if (!is.finite(survey_level_total) || survey_level_total <= 0 ||
        !is.finite(target_adjustable_injury_total) ||
        target_adjustable_injury_total <= 0 ||
        target_adjustable_injury_total >
          maximum_adjustable_injury_total + 1e-8) {
      stop(
        "The survey-derived national injury-level anchor is incompatible with ",
        "the completed mortality envelope.",
        call. = FALSE
      )
    }

    routine_share_active <- injury_normalise_profile(
      routine_active,
      floor = parameters$profile_floor
    )
    survey_share_active <- injury_normalise_profile(
      survey_active,
      floor = parameters$profile_floor
    )

    routine_share <- rep(0, .N)
    survey_share <- rep(0, .N)
    routine_share[active] <- routine_share_active
    survey_share[active] <- survey_share_active

    raw_log_profile_scalar <- rep(0, .N)
    raw_log_profile_scalar[active] <-
      log(survey_share_active) - log(routine_share_active)

    level_ratio <- survey_level_total / routine_level_total
    if (!is.finite(level_ratio) || level_ratio <= 0) {
      stop("The survey-to-routine injury level ratio is invalid.",
           call. = FALSE)
    }

    .(
      Death_Prov = Death_Prov,
      Sex = Sex,
      age5 = age5,
      survey = survey,
      survey_total = survey_total,
      survey_injury_total = survey_injury_total,
      survey_effective_n = survey_effective_n,
      routine_injury_total = routine_injury_total,
      routine_natural_total = routine_natural_total,
      routine_total = routine_total,
      calibration_active = active,
      survey_share = survey_share,
      routine_share = routine_share,
      raw_log_profile_scalar = raw_log_profile_scalar,
      profile_id = paste0("survey_year|", survey_year[[1L]]),
      profile_effective_n = profile_effective_n,
      survey_level_total = survey_level_total,
      derived_survey_level_total = derived_survey_level_total,
      derived_survey_level_source = derived_survey_level_source,
      routine_level_total = routine_level_total,
      routine_adjustable_injury_total = routine_adjustable_injury_total,
      routine_fixed_injury_total = routine_fixed_injury_total,
      target_adjustable_injury_total = target_adjustable_injury_total,
      maximum_adjustable_injury_total = maximum_adjustable_injury_total,
      processed_survey_level_total = processed_survey_level_total,
      processed_survey_all_age_total = processed_survey_all_age_total,
      survey_active_fraction = survey_active_fraction,
      published_survey_level_total = published_survey_level_total,
      published_survey_level_lower = published_survey_level_lower,
      published_survey_level_upper = published_survey_level_upper,
      published_survey_level_source = if (is.null(level_reference)) {
        "No external level reference configured"
      } else {
        as.character(level_reference$source)
      },
      outside_reference_interval = outside_reference_interval,
      derived_to_reference_level_ratio = data.table::fifelse(
        reference_available,
        derived_survey_level_total / published_survey_level_total,
        NA_real_
      ),
      processed_to_published_level_ratio = data.table::fifelse(
        reference_available,
        processed_survey_all_age_total / published_survey_level_total,
        NA_real_
      ),
      point_level_ratio = level_ratio,
      point_log_level_ratio = log(level_ratio)
    )
  }, by = survey_year]

  smoother <- parameters$age_smoothing_matrix
  data.table::setorder(profile, survey_year, Death_Prov, Sex, age5)
  profile[, smoothed_log_profile_scalar := as.numeric(
    smoother %*% raw_log_profile_scalar
  ), by = .(survey_year, Death_Prov, Sex)]
  profile[
    survey_year == anchor_years[[1L]] & age5 %in% 1:2,
    smoothed_log_profile_scalar := 0
  ]
  profile[, profile_factor := injury_safe_exp(smoothed_log_profile_scalar)]

  if (profile[
    !is.finite(smoothed_log_profile_scalar) |
      !is.finite(profile_factor) | profile_factor <= 0 |
      !is.finite(point_log_level_ratio) |
      !is.finite(point_level_ratio) | point_level_ratio <= 0,
    .N
  ]) {
    stop("The injury-envelope level/profile anchor table is invalid.",
         call. = FALSE)
  }

  closure <- profile[calibration_active == TRUE, .(
    survey_share_sum = sum(survey_share),
    routine_share_sum = sum(routine_share)
  ), by = survey_year]
  if (closure[
    abs(survey_share_sum - 1) > 1e-8 |
      abs(routine_share_sum - 1) > 1e-8,
    .N
  ]) {
    stop("The injury-envelope relative profiles do not sum to one.",
         call. = FALSE)
  }

  data.table::setorder(profile, Death_Prov, Sex, age5, survey_year)
  profile[]
}

injury_envelope_annual_factors <- function(anchor_table, cfg) {
  require_package("data.table")
  parameters <- injury_envelope_model_parameters(cfg)
  anchors <- data.table::as.data.table(data.table::copy(anchor_table))
  key <- c("Death_Prov", "Sex", "age5", "survey_year")
  assert_unique_key(anchors, key, "injury-envelope level/profile anchors")

  profile_wide <- data.table::dcast(
    anchors,
    Death_Prov + Sex + age5 ~ survey_year,
    value.var = "smoothed_log_profile_scalar"
  )
  names(profile_wide)[
    names(profile_wide) == as.character(parameters$anchor_years[[1L]])
  ] <- "log_profile_2009"
  names(profile_wide)[
    names(profile_wide) == as.character(parameters$anchor_years[[2L]])
  ] <- "log_profile_2017"
  assert_has_columns(
    profile_wide,
    c("log_profile_2009", "log_profile_2017"),
    "injury-envelope relative-profile anchors"
  )

  level <- unique(anchors[, .(
    survey_year,
    point_log_level_ratio,
    point_level_ratio,
    survey_level_total,
    routine_level_total
  )])
  assert_unique_key(level, "survey_year", "injury-envelope level anchors")
  level_wide <- data.table::dcast(
    level,
    . ~ survey_year,
    value.var = "point_log_level_ratio"
  )
  names(level_wide)[
    names(level_wide) == as.character(parameters$anchor_years[[1L]])
  ] <- "log_level_2009"
  names(level_wide)[
    names(level_wide) == as.character(parameters$anchor_years[[2L]])
  ] <- "log_level_2017"
  assert_has_columns(
    level_wide,
    c("log_level_2009", "log_level_2017"),
    "injury-envelope national level anchors"
  )

  years <- parameters$years
  panel <- profile_wide[rep(seq_len(.N), each = length(years))]
  panel[, DeathYear := rep(years, times = nrow(profile_wide))]
  panel[, time_weight_2017 := data.table::fcase(
    DeathYear <= parameters$anchor_years[[1L]], 0,
    DeathYear >= parameters$anchor_years[[2L]], 1,
    default = (DeathYear - parameters$anchor_years[[1L]]) /
      diff(parameters$anchor_years)
  )]
  panel[, log_profile_factor :=
    (1 - time_weight_2017) * log_profile_2009 +
      time_weight_2017 * log_profile_2017]
  panel[, `:=`(
    profile_factor = injury_safe_exp(log_profile_factor),
    point_log_level_ratio =
      (1 - time_weight_2017) * level_wide$log_level_2009[[1L]] +
        time_weight_2017 * level_wide$log_level_2017[[1L]],
    calibration_active = !(
      DeathYear <= parameters$anchor_years[[1L]] & age5 %in% 1:2
    )
  )]
  panel[, point_level_ratio := injury_safe_exp(point_log_level_ratio)]
  panel <- panel[, .(
    Death_Prov,
    Sex,
    age5,
    DeathYear,
    time_weight_2017,
    calibration_active,
    log_profile_factor,
    profile_factor,
    point_log_level_ratio,
    point_level_ratio
  )]

  if (panel[
    !is.finite(log_profile_factor) |
      !is.finite(profile_factor) | profile_factor <= 0 |
      !is.finite(point_log_level_ratio) |
      !is.finite(point_level_ratio) | point_level_ratio <= 0,
    .N
  ]) {
    stop("The annual injury-envelope level/profile panel is invalid.",
         call. = FALSE)
  }
  assert_unique_key(
    panel,
    c("Death_Prov", "Sex", "age5", "DeathYear"),
    "annual injury-envelope level/profile panel"
  )
  data.table::setorder(panel, Death_Prov, Sex, age5, DeathYear)
  panel[]
}

fit_injury_envelope_model <- function(baseline, envelope_surveys, cfg) {
  parameters <- injury_envelope_model_parameters(cfg)
  anchors <- injury_envelope_anchor_table(baseline, envelope_surveys, cfg)
  annual <- injury_envelope_annual_factors(anchors, cfg)
  artifact <- list(
    version = "1.0",
    method = parameters$method,
    parameters = parameters,
    anchors = anchors,
    annual_point = annual,
    source = paste(
      "Published-compatible IMS 2009 and later-cleaned FAMHIS 2017",
      "eligibility rules and supplied survey weights are used inside the",
      "analysis to estimate national injury-level anchors;",
      "normalised survey weights define the relative province-sex-age profile"
    )
  )
  list(
    anchors = anchors,
    annual_factors = annual,
    artifact = artifact
  )
}

validate_injury_envelope_artifact <- function(artifact) {
  if (!is.list(artifact) || is.null(artifact$anchors) ||
      is.null(artifact$annual_point) || is.null(artifact$parameters)) {
    stop("The injury-envelope model artifact is incomplete.", call. = FALSE)
  }
  anchors <- data.table::as.data.table(artifact$anchors)
  annual <- data.table::as.data.table(artifact$annual_point)
  assert_has_columns(
    anchors,
    c(
      "Death_Prov", "Sex", "age5", "survey_year",
      "survey_injury_total", "survey_effective_n",
      "survey_share", "routine_share", "profile_effective_n",
      "smoothed_log_profile_scalar", "profile_factor",
      "survey_level_total", "derived_survey_level_total",
      "derived_survey_level_source", "routine_level_total",
      "routine_adjustable_injury_total", "routine_fixed_injury_total",
      "target_adjustable_injury_total", "maximum_adjustable_injury_total",
      "processed_survey_level_total", "processed_survey_all_age_total",
      "published_survey_level_total", "published_survey_level_lower",
      "published_survey_level_upper",
      "outside_reference_interval",
      "derived_to_reference_level_ratio",
      "processed_to_published_level_ratio",
      "point_level_ratio", "point_log_level_ratio"
    ),
    "injury-envelope level/profile anchors"
  )
  assert_unique_key(
    anchors,
    c("Death_Prov", "Sex", "age5", "survey_year"),
    "injury-envelope level/profile anchors"
  )
  if (!identical(sort(unique(anchors$survey_year)), c(2009L, 2017L))) {
    stop("The injury-envelope artifact must contain 2009 and 2017 anchors.",
         call. = FALSE)
  }
  level_audit <- unique(anchors[, .(
    survey_year,
    survey_level_total,
    derived_survey_level_total,
    derived_survey_level_source,
    processed_survey_all_age_total,
    published_survey_level_total,
    published_survey_level_lower,
    published_survey_level_upper,
    outside_reference_interval,
    derived_to_reference_level_ratio,
    processed_to_published_level_ratio
  )])
  assert_unique_key(level_audit, "survey_year", "injury-level anchor audit")
  if (level_audit[
    !is.finite(survey_level_total) | survey_level_total <= 0 |
      !is.finite(derived_survey_level_total) |
      derived_survey_level_total <= 0 |
      abs(survey_level_total - derived_survey_level_total) >
        1e-10 * pmax(1, abs(derived_survey_level_total)) |
      !is.finite(processed_survey_all_age_total) |
      processed_survey_all_age_total <= 0,
    .N
  ]) {
    stop("The survey-derived injury-level anchor audit contains invalid values.",
         call. = FALSE)
  }
  reference_rows <- level_audit[
    is.finite(published_survey_level_total) |
      is.finite(published_survey_level_lower) |
      is.finite(published_survey_level_upper)
  ]
  if (reference_rows[
    !is.finite(published_survey_level_total) |
      !is.finite(published_survey_level_lower) |
      !is.finite(published_survey_level_upper),
    .N
  ]) {
    stop("An external injury-level reference is only partially specified.",
         call. = FALSE)
  }
  assert_has_columns(
    annual,
    c(
      "Death_Prov", "Sex", "age5", "DeathYear",
      "log_profile_factor", "profile_factor",
      "point_log_level_ratio", "point_level_ratio", "calibration_active"
    ),
    "injury-envelope annual level/profile factors"
  )
  assert_unique_key(
    annual,
    c("Death_Prov", "Sex", "age5", "DeathYear"),
    "injury-envelope annual level/profile factors"
  )
  if (annual[
    !is.finite(log_profile_factor) |
      !is.finite(profile_factor) | profile_factor <= 0 |
      !is.finite(point_log_level_ratio) |
      !is.finite(point_level_ratio) | point_level_ratio <= 0,
    .N
  ]) {
    stop("The injury-envelope artifact contains invalid level/profile factors.",
         call. = FALSE)
  }
  invisible(TRUE)
}

injury_draw_dirichlet_profile <- function(shares, effective_n, alpha_floor) {
  p <- injury_normalise_profile(shares, floor = alpha_floor)
  if (!is.finite(effective_n) || effective_n <= 0 || is.infinite(effective_n)) {
    return(p)
  }
  alpha <- pmax(p * effective_n, alpha_floor)
  draw <- stats::rgamma(length(alpha), shape = alpha, rate = 1)

  # A Gamma variate is strictly positive mathematically, but for very small
  # shape parameters R can return an exact floating-point zero. Regenerate only
  # those machine-boundary values with the inverse CDF; if the quantile still
  # underflows, use the smallest positive representable double. This is a
  # numerical repair of the same Dirichlet distribution, not a variance floor.
  bad <- !is.finite(draw) | draw <= 0
  if (any(bad)) {
    u <- stats::runif(sum(bad), min = .Machine$double.xmin, max = 1)
    replacement <- stats::qgamma(
      u,
      shape = alpha[bad],
      rate = 1,
      lower.tail = TRUE,
      log.p = FALSE
    )
    replacement[!is.finite(replacement) | replacement <= 0] <-
      .Machine$double.xmin
    draw[bad] <- replacement
  }
  if (any(!is.finite(draw)) || any(draw <= 0) || sum(draw) <= 0) {
    stop("The injury-envelope profile draw is invalid.", call. = FALSE)
  }

  # Normalise on the log scale so a very large Gamma draw cannot overflow the
  # denominator and a very small positive draw is not rounded to zero.
  log_draw <- log(draw)
  log_draw <- log_draw - max(log_draw)
  result <- exp(log_draw)
  result <- pmax(result, .Machine$double.xmin)
  result <- result / sum(result)
  if (any(!is.finite(result)) || any(result <= 0) ||
      abs(sum(result) - 1) > 1e-12) {
    stop("The injury-envelope profile draw did not form an open simplex.",
         call. = FALSE)
  }
  result
}

injury_solve_log_odds_intercept <- function(
    injury,
    natural,
    log_scalar,
    target,
    tolerance = 1e-12) {
  injury <- as.numeric(injury)
  natural <- as.numeric(natural)
  log_scalar <- as.numeric(log_scalar)
  eligible <- injury + natural
  if (!length(injury) || sum(eligible) <= tolerance) return(0)
  target <- as.numeric(target)
  if (!is.finite(target) || target < 0 || target > sum(eligible) + tolerance) {
    stop("The injury calibration target is outside the eligible envelope.",
         call. = FALSE)
  }
  objective <- function(delta) {
    eta <- log(injury) - log(natural) + log_scalar + delta
    sum(eligible * stats::plogis(eta)) - target
  }
  lower <- -50
  upper <- 50
  f_lower <- objective(lower)
  f_upper <- objective(upper)
  iteration <- 0L
  while ((f_lower > tolerance || f_upper < -tolerance) && iteration < 20L) {
    if (f_lower > tolerance) lower <- lower - 50 * 2^iteration
    if (f_upper < -tolerance) upper <- upper + 50 * 2^iteration
    f_lower <- objective(lower)
    f_upper <- objective(upper)
    iteration <- iteration + 1L
  }
  if (f_lower > tolerance || f_upper < -tolerance) {
    stop("Could not bracket the injury calibration intercept.",
         call. = FALSE)
  }
  if (abs(f_lower) <= tolerance) return(lower)
  if (abs(f_upper) <= tolerance) return(upper)
  stats::uniroot(
    objective,
    interval = c(lower, upper),
    tol = tolerance,
    maxiter = 200L
  )$root
}

apply_injury_envelope_adjustment <- function(
    data,
    factors,
    profile_column = NULL,
    level_column = NULL,
    profile_log_column = NULL,
    level_log_column = NULL,
    factor_column = NULL,
    tolerance = 1e-10) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  factor_table <- data.table::as.data.table(data.table::copy(factors))
  factor_key <- c("Death_Prov", "Sex", "DeathYear", "age5")
  cell <- c("Death_Prov", "Sex", "DeathYear", "Popgroup", "age5")
  assert_has_columns(
    x,
    c(cell, "nbdcode", "Deaths"),
    "injury-envelope adjustment input"
  )

  # Backward-compatible argument handling for the stage wrapper. The final
  # point panel uses profile_factor + point_level_ratio; stochastic draws use
  # draw_profile_factor + draw_level_ratio.
  if (is.null(profile_column)) {
    profile_column <- if ("draw_profile_factor" %in% names(factor_table)) {
      "draw_profile_factor"
    } else {
      "profile_factor"
    }
  }
  if (is.null(level_column)) {
    level_column <- if ("draw_level_ratio" %in% names(factor_table)) {
      "draw_level_ratio"
    } else {
      "point_level_ratio"
    }
  }
  if (is.null(profile_log_column)) {
    profile_log_column <- if ("draw_log_profile_factor" %in% names(factor_table)) {
      "draw_log_profile_factor"
    } else if ("log_profile_factor" %in% names(factor_table)) {
      "log_profile_factor"
    } else {
      NULL
    }
  }
  if (is.null(level_log_column)) {
    level_log_column <- if ("draw_log_level_ratio" %in% names(factor_table)) {
      "draw_log_level_ratio"
    } else if ("point_log_level_ratio" %in% names(factor_table)) {
      "point_log_level_ratio"
    } else {
      NULL
    }
  }
  # `factor_column` is retained only so an older stage wrapper fails safely
  # into the new point columns rather than using the obsolete injury-share odds.
  if (!is.null(factor_column) &&
      factor_column %in% names(factor_table) &&
      !profile_column %in% names(factor_table)) {
    profile_column <- factor_column
  }

  required_factor_columns <- c(factor_key, profile_column, level_column)
  if (!is.null(profile_log_column)) {
    required_factor_columns <- c(required_factor_columns, profile_log_column)
  }
  if (!is.null(level_log_column)) {
    required_factor_columns <- c(required_factor_columns, level_log_column)
  }
  assert_has_columns(
    factor_table,
    unique(required_factor_columns),
    "injury-envelope level/profile panel"
  )
  assert_unique_key(
    factor_table,
    factor_key,
    "injury-envelope level/profile panel"
  )
  factor_table[, `:=`(
    profile_factor__ = as.numeric(get(profile_column)),
    level_ratio__ = as.numeric(get(level_column)),
    log_profile_factor__ = if (is.null(profile_log_column)) {
      log(as.numeric(get(profile_column)))
    } else {
      as.numeric(get(profile_log_column))
    },
    log_level_ratio__ = if (is.null(level_log_column)) {
      log(as.numeric(get(level_column)))
    } else {
      as.numeric(get(level_log_column))
    }
  )]
  if (!"calibration_active" %in% names(factor_table)) {
    factor_table[, calibration_active := TRUE]
  }
  factor_table[, calibration_active := as.logical(calibration_active)]
  if (factor_table[
    !is.finite(log_profile_factor__) |
      !is.finite(log_level_ratio__) |
      !is.finite(profile_factor__) | profile_factor__ <= 0 |
      !is.finite(level_ratio__) | level_ratio__ <= 0 |
      is.na(calibration_active),
    .N
  ]) {
    stop("The injury-envelope level/profile panel contains invalid values.",
         call. = FALSE)
  }

  audit <- x[, .(
    total_before = sum(Deaths, na.rm = TRUE),
    injury_before = sum(Deaths[nbdcode %in% INJURY_CODES], na.rm = TRUE),
    natural_before = sum(Deaths[!nbdcode %in% INJURY_CODES], na.rm = TRUE)
  ), by = cell]
  audit <- merge(
    audit,
    factor_table[, c(
      factor_key,
      "profile_factor__",
      "level_ratio__",
      "log_profile_factor__",
      "log_level_ratio__",
      "calibration_active"
    ), with = FALSE],
    by = factor_key,
    all.x = TRUE,
    sort = FALSE
  )
  if (audit[
    is.na(profile_factor__) | is.na(level_ratio__) |
      is.na(log_profile_factor__) | is.na(log_level_ratio__) |
      is.na(calibration_active),
    .N
  ]) {
    stop("The injury-envelope level/profile panel does not cover all mortality cells.",
         call. = FALSE)
  }
  audit[, `:=`(
    eligible_before = injury_before + natural_before,
    adjustable = calibration_active & injury_before > tolerance &
      natural_before > tolerance,
    row_id__ = .I
  )]

  calibrated <- audit[, {
    adjustable_rows <- which(adjustable)
    fixed_rows <- which(!adjustable)
    injury_after <- injury_before
    natural_after <- natural_before
    effective_profile_factor <- rep(1, .N)
    intercept <- 0

    level_log_values <- unique(log_level_ratio__)
    level_log_values <- level_log_values[is.finite(level_log_values)]
    if (length(level_log_values) != 1L) {
      stop("The national injury-level log ratio is not unique within year.",
           call. = FALSE)
    }
    level_log_ratio_year <- level_log_values[[1L]]
    level_ratio_year <- injury_safe_exp(level_log_ratio_year)

    fixed_injury <- sum(injury_before[fixed_rows], na.rm = TRUE)
    routine_adjustable_injury <- sum(
      injury_before[adjustable_rows],
      na.rm = TRUE
    )
    routine_total_injury <- fixed_injury + routine_adjustable_injury
    target_total_injury <- routine_total_injury * level_ratio_year
    target_adjustable_injury <- target_total_injury - fixed_injury

    if (length(adjustable_rows)) {
      maximum_adjustable <- sum(eligible_before[adjustable_rows], na.rm = TRUE)
      if (!is.finite(target_adjustable_injury) ||
          target_adjustable_injury < 0 ||
          target_adjustable_injury > maximum_adjustable + tolerance) {
        stop(
          "The survey-calibrated national injury target is outside the ",
          "completed mortality envelope in year ", DeathYear[[1L]], ".",
          call. = FALSE
        )
      }
      intercept <- injury_solve_log_odds_intercept(
        injury = injury_before[adjustable_rows],
        natural = natural_before[adjustable_rows],
        log_scalar = log_profile_factor__[adjustable_rows],
        target = target_adjustable_injury,
        tolerance = min(tolerance, 1e-12)
      )
      effective_log_profile_factor <-
        log_profile_factor__[adjustable_rows] + intercept
      effective_profile_factor[adjustable_rows] <-
        injury_safe_exp(effective_log_profile_factor)
      eta <- log(injury_before[adjustable_rows]) -
        log(natural_before[adjustable_rows]) +
        effective_log_profile_factor
      injury_after[adjustable_rows] <-
        eligible_before[adjustable_rows] * stats::plogis(eta)
      natural_after[adjustable_rows] <-
        eligible_before[adjustable_rows] - injury_after[adjustable_rows]
    }

    .(
      row_id__ = row_id__,
      centering_log_intercept = intercept,
      effective_profile_factor__ = effective_profile_factor,
      injury_after = injury_after,
      natural_after = natural_after,
      level_ratio_year = level_ratio_year,
      fixed_injury_year = fixed_injury,
      routine_adjustable_injury_year = routine_adjustable_injury,
      routine_total_injury_year = routine_total_injury,
      target_adjustable_injury_year = target_adjustable_injury,
      target_total_injury_year = target_total_injury
    )
  }, by = DeathYear]

  # `calibrated` carries DeathYear as its grouping column. Merge on both
  # identifiers so data.table does not create DeathYear.x/DeathYear.y and
  # remove the canonical DeathYear name needed by the annual checks below.
  audit <- merge(
    audit,
    calibrated,
    by = c("row_id__", "DeathYear"),
    all.x = TRUE,
    sort = FALSE
  )
  assert_has_columns(
    audit,
    cell,
    "injury-envelope calibration audit"
  )
  audit[abs(injury_after) <= tolerance, injury_after := 0]
  audit[abs(natural_after) <= tolerance, natural_after := 0]
  if (audit[
    !is.finite(injury_after) | injury_after < -tolerance |
      !is.finite(natural_after) | natural_after < -tolerance,
    .N
  ]) {
    stop("The bounded injury level/profile calibration produced invalid deaths.",
         call. = FALSE)
  }
  audit[, `:=`(
    injury_scale__ = data.table::fifelse(
      injury_before > 0,
      injury_after / injury_before,
      1
    ),
    natural_scale__ = data.table::fifelse(
      natural_before > 0,
      natural_after / natural_before,
      1
    ),
    injury_change = injury_after - injury_before,
    injury_share_before = data.table::fifelse(
      eligible_before > 0,
      injury_before / eligible_before,
      0
    ),
    injury_share_after = data.table::fifelse(
      eligible_before > 0,
      injury_after / eligible_before,
      0
    )
  )]
  if (audit[
    !is.finite(injury_scale__) | injury_scale__ < 0 |
      !is.finite(natural_scale__) | natural_scale__ < 0,
    .N
  ]) {
    stop("The bounded injury level/profile scaling factors are invalid.",
         call. = FALSE)
  }

  year_check <- audit[, .(
    injury_before_year = sum(injury_before),
    injury_after_year = sum(injury_after),
    target_total_injury_year = unique(target_total_injury_year)
  ), by = DeathYear]
  year_check[, error := injury_after_year - target_total_injury_year]
  if (year_check[
    abs(error) > 1e-8 * pmax(1, abs(target_total_injury_year)),
    .N
  ]) {
    stop("The injury calibration did not reproduce the annual target injury totals.",
         call. = FALSE)
  }

  x <- merge(
    x,
    audit[, c(cell, "injury_scale__", "natural_scale__"), with = FALSE],
    by = cell,
    all.x = TRUE,
    sort = FALSE
  )
  x[nbdcode %in% INJURY_CODES, Deaths := Deaths * injury_scale__]
  x[!nbdcode %in% INJURY_CODES, Deaths := Deaths * natural_scale__]
  x[, c("injury_scale__", "natural_scale__") := NULL]
  x <- x[, .(Deaths = sum(Deaths, na.rm = TRUE)), by = .(
    Death_Prov, Sex, DeathYear, Popgroup, age5, nbdcode
  )]
  assert_nonnegative(x, "Deaths")

  after <- x[, .(
    total_after = sum(Deaths, na.rm = TRUE),
    injury_after_check = sum(Deaths[nbdcode %in% INJURY_CODES], na.rm = TRUE),
    natural_after_check = sum(Deaths[!nbdcode %in% INJURY_CODES], na.rm = TRUE)
  ), by = cell]
  audit <- merge(audit, after, by = cell, all.x = TRUE, sort = FALSE)
  audit[, `:=`(
    total_error = total_after - total_before,
    injury_error = injury_after_check - injury_after,
    natural_error = natural_after_check - natural_after
  )]
  scale <- pmax(1, abs(audit$total_before))
  if (any(abs(audit$total_error) > 1e-8 * scale)) {
    stop("The injury calibration did not preserve population-group cell totals.",
         call. = FALSE)
  }

  list(
    data = x[],
    audit = audit[],
    diagnostics = list(
      maximum_total_absolute_error = max(abs(audit$total_error), na.rm = TRUE),
      maximum_total_relative_error = max(
        abs(audit$total_error) / scale,
        na.rm = TRUE
      ),
      minimum_profile_factor = min(audit$profile_factor__, na.rm = TRUE),
      maximum_profile_factor = max(audit$profile_factor__, na.rm = TRUE),
      minimum_level_ratio = min(audit$level_ratio__, na.rm = TRUE),
      maximum_level_ratio = max(audit$level_ratio__, na.rm = TRUE),
      minimum_effective_profile_factor = min(
        audit$effective_profile_factor__,
        na.rm = TRUE
      ),
      maximum_effective_profile_factor = max(
        audit$effective_profile_factor__,
        na.rm = TRUE
      ),
      injury_before = sum(audit$injury_before),
      injury_after = sum(audit$injury_after),
      calibration_scope = "national year",
      all_cause_scope = "province-sex-year-population-group-age",
      calibration_intercept_min = min(
        audit$centering_log_intercept,
        na.rm = TRUE
      ),
      calibration_intercept_max = max(
        audit$centering_log_intercept,
        na.rm = TRUE
      )
    )
  )
}



apply_injury_fractions <- function(injury_cod, fractions) {
  require_package("data.table")

  mortality <- data.table::as.data.table(data.table::copy(injury_cod))
  assert_has_columns(
    mortality,
    c("Death_Prov", "Sex", "Popgroup", "age5", "DeathYear", "Deaths"),
    "injury mortality envelope"
  )
  mortality[, Deaths := suppressWarnings(as.numeric(Deaths))]
  if (mortality[!is.finite(Deaths) | Deaths < 0, .N]) {
    stop("Injury mortality counts must be finite and non-negative.", call. = FALSE)
  }

  totals <- mortality[, .(
    total_injury_deaths = sum(Deaths)
  ), by = .(Death_Prov, Sex, Popgroup, age5, DeathYear)]
  keys_total <- c("Death_Prov", "Sex", "Popgroup", "age5", "DeathYear")

  f <- data.table::as.data.table(data.table::copy(fractions))
  assert_has_columns(
    f,
    c("Death_Prov", "Sex", "Popgroup", "age5", "year", "nbdcode", "cf_final"),
    "injury fractions"
  )
  f <- f[, .(
    Death_Prov, Sex, Popgroup, age5,
    DeathYear = as.integer(year),
    nbdcode,
    cf_final
  )]
  assert_unique_key(
    f,
    c(keys_total, "nbdcode"),
    "injury fractions"
  )
  if (f[!is.finite(cf_final) | cf_final <= 0, .N]) {
    stop("Injury fractions must be finite and strictly positive.", call. = FALSE)
  }
  fraction_check <- f[, .(
    fraction_sum = sum(cf_final)
  ), by = keys_total]
  if (fraction_check[abs(fraction_sum - 1) > 1e-10, .N]) {
    stop("Injury fractions must sum to one within every mortality stratum.", call. = FALSE)
  }

  out <- merge(
    totals,
    f,
    by = keys_total,
    all.x = TRUE,
    allow.cartesian = TRUE,
    sort = FALSE
  )
  missing_strata <- out[is.na(cf_final), unique(.SD), .SDcols = keys_total]
  if (nrow(missing_strata)) {
    stop(
      "Injury fractions are missing for ", nrow(missing_strata),
      " mortality stratum/strata. First missing row: ",
      paste(unlist(missing_strata[1]), collapse = "/"),
      call. = FALSE
    )
  }
  out[, Deaths := total_injury_deaths * cf_final]

  envelope_check <- out[, .(
    expected_deaths = unique(total_injury_deaths),
    n_expected_values = data.table::uniqueN(total_injury_deaths),
    allocated_deaths = sum(Deaths)
  ), by = keys_total]
  if (envelope_check[n_expected_values != 1L, .N]) {
    stop("The injury mortality envelope is not unique by stratum.", call. = FALSE)
  }
  envelope_check[, tolerance := 1e-8 * pmax(1, abs(expected_deaths))]
  if (envelope_check[
    abs(allocated_deaths - expected_deaths) > tolerance,
    .N
  ]) {
    stop("Cause allocation did not preserve every injury mortality stratum.", call. = FALSE)
  }

  assert_total_preserved(
    sum(totals$total_injury_deaths),
    sum(out$Deaths),
    tolerance = 1e-8,
    label = "injury mortality envelope"
  )
  out[, `:=`(cf_final = NULL, total_injury_deaths = NULL, Inj = 1L)]
  out <- out[, .(
    Death_Prov, Sex, DeathYear, Popgroup, age5, nbdcode, Deaths, Inj
  )]
  assert_nonnegative(out, "Deaths")
  assert_unique_key(
    out,
    c("Death_Prov", "Sex", "DeathYear", "Popgroup", "age5", "nbdcode", "Inj"),
    "final injury estimates"
  )
  out[]
}


injury_model_diagnostics <- function(
    surveys,
    fractions,
    cfg = NULL,
    fitted_model = NULL) {
  require_package("data.table")

  if (is.null(cfg)) cfg <- list(settings = list(
    start_year = min(fractions$year),
    end_year = max(fractions$year),
    injury_fraction_method = "nims_ims_famhis_alr_linear_triangular_ma",
    injury_nims_year = 2000L,
    injury_ims_year = 2009L,
    injury_famhis_year = 2017L,
    injury_fraction_floor = 1e-8,
    injury_bias_correction_floor = 1e-5,
    injury_alr_reference_code = 139L,
    injury_smoothing_window = 5L
  ))
  model <- fitted_model %||% fit_injury_fraction_model(surveys, cfg)
  parameters <- model$parameters
  observed <- model$source_fractions

  source_summary <- observed[, .(
    observed_count = sum(observed_count, na.rm = TRUE),
    harmonised_count = sum(harmonised_count, na.rm = TRUE),
    effective_n = max(survey_effective_n, na.rm = TRUE),
    cells = .N,
    empty_cells_borrowed = sum(grepl("^Borrowed", fraction_source)),
    bias_corrected_cells = sum(correction_applied, na.rm = TRUE),
    numerical_floor_cells = sum(numerical_floor_applied, na.rm = TRUE)
  ), by = .(survey, year)]
  source_summary[, record_type := "Survey input"]
  data.table::setcolorder(source_summary, c("record_type", "survey", "year"))

  comparison <- model$survey_model_comparison %||%
    injury_survey_model_comparison(observed, fractions)
  survey_fit <- comparison[, .(
    mean_absolute_difference = mean(absolute_difference, na.rm = TRUE),
    p95_absolute_difference = as.numeric(stats::quantile(
      absolute_difference, 0.95, na.rm = TRUE
    )),
    maximum_absolute_difference = max(absolute_difference, na.rm = TRUE)
  ), by = .(survey, year)]
  survey_fit[, record_type := "Survey-model comparison"]
  data.table::setcolorder(survey_fit, c("record_type", "survey", "year"))

  closure <- fractions[, .(fraction_sum = sum(cf_final)),
    by = .(Death_Prov, Sex, Popgroup, age5, year)]
  panel_summary <- data.table::data.table(
    record_type = "Modelled panel",
    method = parameters$method,
    interpolation = "Piecewise linear in hierarchical ALR space",
    smoother = paste0(parameters$smoothing_window, "-year centred triangular moving average"),
    tail_policy = "Flat survey-boundary tails before smoothing",
    start_year = min(fractions$year),
    end_year = max(fractions$year),
    rows = nrow(fractions),
    minimum_fraction = min(fractions$cf_final),
    maximum_fraction = max(fractions$cf_final),
    maximum_closure_error = max(abs(closure$fraction_sum - 1)),
    survey_policy = paste(
      "Harmonised survey fractions define the common ALR trajectory; the final",
      "smoothed curve is not reset at survey years"
    ),
    uncertainty_policy = paste(
      "IMS/FAMHIS use the same stratified PSU replicate as the injury level and",
      "profile; NIMS uses count-based composition uncertainty"
    )
  )

  trajectory_summary <- data.table::copy(model$model_summaries)
  trajectory_summary[, record_type := "Interpolation specification"]

  data.table::rbindlist(
    list(source_summary, survey_fit, panel_summary, trajectory_summary),
    use.names = TRUE,
    fill = TRUE
  )[]
}
