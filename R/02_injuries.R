# Injury survey preparation ----------------------------------------------------
#
# NIMS 2000, IMS 2009 and FAMHIS 2017 are harmonised to a common province x
# sex x population-group x age x cause grid. NIMS is national by sex, age and
# cause; it is expanded to province x population group using the observed IMS
# 2009 distribution for the same sex x age x cause. This preserves the NIMS
# national totals while making the spatial information explicitly derived.

standardise_injury_columns <- function(data, aliases) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  for (target in names(aliases)) {
    x <- rename_first_match(x, target, aliases[[target]], required = TRUE)
  }
  x
}


# Build a stable character key from one or more columns. This avoids fragile
# data.table `..` expressions inside nested donor-reference objects and works
# identically for one-column and multi-column reference levels.
injury_reference_key <- function(data, columns) {
  x <- data.table::as.data.table(data)
  if (!length(columns)) return(rep("__national__", nrow(x)))

  missing <- setdiff(columns, names(x))
  if (length(missing)) {
    stop(
      "Cannot construct an injury donor key; missing column(s): ",
      paste(missing, collapse = ", "),
      call. = FALSE
    )
  }

  values <- lapply(columns, function(column) {
    value <- as.character(x[[column]])
    value[is.na(value)] <- "<NA>"
    value
  })
  do.call(paste, c(values, list(sep = "\x1f")))
}


# Survey-information helpers --------------------------------------------------
#
# Weighted injury totals are not treated as independent sample sizes. IMS and
# FAMHIS production uncertainty is generated by resampling their sampled PSUs
# within survey strata, so their national level, demographic profile and
# well-specified cause counts move jointly. Kish effective sizes are retained
# only as descriptive audit quantities and compatibility metadata. NIMS contains
# count cells and therefore uses count-equivalent composition uncertainty.

kish_effective_sample_size <- function(weights) {
  w <- suppressWarnings(as.numeric(weights))
  w <- w[is.finite(w) & w > 0]
  if (!length(w)) return(0)
  denominator <- sum(w^2)
  if (!is.finite(denominator) || denominator <= 0) return(0)
  as.numeric(sum(w)^2 / denominator)
}


# Stratified PSU bootstrap helpers ---------------------------------------------
#
# IMS and FAMHIS both retain sampled mortuary/facility identifiers and survey
# strata. Version 1 uses those design variables to estimate uncertainty in the
# national injury level and to calibrate the Dirichlet information used for the
# demographic profile and well-specified cause composition. Singleton sampled
# strata are held fixed, matching the usual treatment of certainty/singleton
# PSUs in a non-parametric within-stratum bootstrap.

injury_bootstrap_settings <- function(cfg = NULL) {
  settings <- cfg$settings %||% list()
  n_replicates <- suppressWarnings(as.integer(
    settings$injury_survey_bootstrap_replicates %||% 1000L
  ))
  seed <- suppressWarnings(as.integer(
    settings$injury_survey_bootstrap_seed %||% 20260812L
  ))
  if (length(n_replicates) != 1L || is.na(n_replicates) ||
      n_replicates < 200L) {
    stop("injury_survey_bootstrap_replicates must be at least 200.",
         call. = FALSE)
  }
  if (length(seed) != 1L || is.na(seed)) {
    stop("injury_survey_bootstrap_seed must be one finite integer.",
         call. = FALSE)
  }
  list(n_replicates = n_replicates, seed = seed)
}

injury_psu_bootstrap_total <- function(
    data,
    stratum,
    psu,
    weight,
    n_replicates,
    seed) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  assert_has_columns(x, c(stratum, psu, weight), "injury PSU bootstrap")
  x[, bootstrap_weight__ := suppressWarnings(as.numeric(get(weight)))]
  x <- x[
    is.finite(bootstrap_weight__) & bootstrap_weight__ >= 0 &
      !is.na(get(stratum)) & !is.na(get(psu))
  ]
  if (!nrow(x)) {
    stop("The injury PSU bootstrap has no eligible records.", call. = FALSE)
  }
  grouped <- x[, .(
    bootstrap_value__ = sum(bootstrap_weight__, na.rm = TRUE)
  ), by = c(stratum, psu)]
  point <- sum(grouped$bootstrap_value__, na.rm = TRUE)
  if (!is.finite(point) || point <= 0) {
    stop("The injury PSU bootstrap point total is not positive.", call. = FALSE)
  }

  set.seed(as.integer(seed))
  replicates <- numeric(n_replicates)
  for (value in unique(grouped[[stratum]])) {
    block <- grouped[get(stratum) == value, bootstrap_value__]
    n_psu <- length(block)
    if (n_psu == 1L) {
      replicates <- replicates + block[[1L]]
    } else {
      index <- matrix(
        sample.int(n_psu, n_replicates * n_psu, replace = TRUE),
        nrow = n_replicates,
        ncol = n_psu
      )
      replicates <- replicates + rowSums(matrix(
        block[index],
        nrow = n_replicates,
        ncol = n_psu
      ))
    }
  }
  if (any(!is.finite(replicates)) || any(replicates <= 0)) {
    stop("The injury PSU bootstrap produced an invalid total replicate.",
         call. = FALSE)
  }
  list(point = point, replicates = replicates)
}

injury_psu_bootstrap_composition <- function(
    data,
    stratum,
    psu,
    category,
    weight,
    levels,
    n_replicates,
    seed) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  assert_has_columns(
    x,
    c(stratum, psu, category, weight),
    "injury PSU composition bootstrap"
  )
  levels <- as.character(levels)
  x[, bootstrap_category__ := as.character(get(category))]
  x[, bootstrap_weight__ := suppressWarnings(as.numeric(get(weight)))]
  x <- x[
    bootstrap_category__ %in% levels &
      is.finite(bootstrap_weight__) & bootstrap_weight__ >= 0 &
      !is.na(get(stratum)) & !is.na(get(psu))
  ]
  if (!nrow(x)) {
    stop("The injury PSU composition bootstrap has no eligible records.",
         call. = FALSE)
  }
  grouped <- x[, .(
    bootstrap_value__ = sum(bootstrap_weight__, na.rm = TRUE)
  ), by = c(stratum, psu, "bootstrap_category__")]

  point <- setNames(numeric(length(levels)), levels)
  replicates <- matrix(
    0,
    nrow = n_replicates,
    ncol = length(levels),
    dimnames = list(NULL, levels)
  )
  set.seed(as.integer(seed))
  for (value in unique(grouped[[stratum]])) {
    block <- grouped[get(stratum) == value]
    psu_values <- unique(block[[psu]])
    wide <- data.table::CJ(
      bootstrap_psu__ = psu_values,
      bootstrap_category__ = levels,
      unique = TRUE
    )
    names(wide)[names(wide) == "bootstrap_psu__"] <- psu
    wide <- merge(
      wide,
      block[, c(psu, "bootstrap_category__", "bootstrap_value__"), with = FALSE],
      by = c(psu, "bootstrap_category__"),
      all.x = TRUE,
      sort = FALSE
    )
    wide[is.na(bootstrap_value__), bootstrap_value__ := 0]
    matrix_block <- data.table::dcast(
      wide,
      stats::as.formula(paste(psu, "~ bootstrap_category__")),
      value.var = "bootstrap_value__",
      fill = 0
    )
    missing_levels <- setdiff(levels, names(matrix_block))
    if (length(missing_levels)) matrix_block[, (missing_levels) := 0]
    values <- as.matrix(matrix_block[, ..levels])
    storage.mode(values) <- "double"
    point <- point + colSums(values)
    n_psu <- nrow(values)
    if (n_psu == 1L) {
      replicates <- sweep(replicates, 2L, values[1L, ], `+`)
    } else {
      index <- matrix(
        sample.int(n_psu, n_replicates * n_psu, replace = TRUE),
        nrow = n_replicates,
        ncol = n_psu
      )
      for (column in seq_len(n_psu)) {
        replicates <- replicates + values[index[, column], , drop = FALSE]
      }
    }
  }
  if (!is.finite(sum(point)) || sum(point) <= 0 ||
      any(!is.finite(replicates)) ||
      any(rowSums(replicates) <= 0)) {
    stop("The injury PSU composition bootstrap is invalid.", call. = FALSE)
  }
  list(point = point, replicates = replicates)
}

injury_bootstrap_level_summary <- function(point, replicates) {
  point <- suppressWarnings(as.numeric(point))
  replicates <- suppressWarnings(as.numeric(replicates))
  replicates <- replicates[is.finite(replicates) & replicates > 0]
  if (!is.finite(point) || point <= 0 || length(replicates) < 100L) {
    stop("The injury level bootstrap summary is not estimable.", call. = FALSE)
  }
  relative_log <- log(replicates / point)
  list(
    standard_error = stats::sd(replicates),
    lower = as.numeric(stats::quantile(
      replicates, 0.025, names = FALSE, type = 8
    )),
    upper = as.numeric(stats::quantile(
      replicates, 0.975, names = FALSE, type = 8
    )),
    log_sd = stats::sd(relative_log),
    n_replicates = length(replicates)
  )
}

injury_dirichlet_effective_n_from_bootstrap <- function(
    point_counts,
    replicate_counts,
    fallback = 0) {
  point <- suppressWarnings(as.numeric(point_counts))
  replicate_counts <- as.matrix(replicate_counts)
  storage.mode(replicate_counts) <- "double"
  total <- sum(point)
  replicate_total <- rowSums(replicate_counts)
  valid <- is.finite(replicate_total) & replicate_total > 0
  if (!is.finite(total) || total <= 0 || sum(valid) < 100L) {
    return(as.numeric(fallback))
  }
  p <- pmax(point, 0) / total
  shares <- replicate_counts[valid, , drop = FALSE] /
    replicate_total[valid]
  variance <- apply(shares, 2L, stats::var)
  numerator <- 1 - sum(p^2)
  denominator <- sum(variance[is.finite(variance) & variance >= 0])
  estimate <- numerator / denominator - 1
  if (!is.finite(estimate) || estimate <= 0) {
    return(as.numeric(fallback))
  }
  as.numeric(estimate)
}

