allocate_injury_envelope_effective_n <- function(
    data,
    count_column,
    effective_total,
    output_column = "survey_effective_n",
    strata = c("Death_Prov", "Sex", "age5"),
    eligible = NULL) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  assert_has_columns(x, c(strata, count_column), "injury-envelope effective-size allocation")

  effective_total <- suppressWarnings(as.numeric(effective_total))
  if (length(effective_total) != 1L || !is.finite(effective_total) ||
      effective_total < 0) {
    stop(
      "The injury-envelope survey effective sample size must be finite and non-negative.",
      call. = FALSE
    )
  }
  if (is.null(eligible)) eligible <- rep(TRUE, nrow(x))
  eligible <- as.logical(eligible)
  if (length(eligible) != nrow(x) || anyNA(eligible)) {
    stop("The injury-envelope effective-size eligibility flag is invalid.",
         call. = FALSE)
  }
  x[, eligible__ := eligible]

  stratum <- x[eligible__ == TRUE, .(
    weighted_total__ = sum(as.numeric(get(count_column)), na.rm = TRUE)
  ), by = strata]
  grand_total <- sum(stratum$weighted_total__, na.rm = TRUE)
  if (grand_total > 0 && effective_total > 0) {
    stratum[, effective_n__ := effective_total * weighted_total__ / grand_total]
  } else {
    stratum[, effective_n__ := 0]
  }
  x <- merge(
    x,
    stratum[, c(strata, "effective_n__"), with = FALSE],
    by = strata,
    all.x = TRUE,
    sort = FALSE
  )
  x[is.na(effective_n__), effective_n__ := 0]
  x[, (output_column) := pmax(0, as.numeric(effective_n__))]
  x[, c("effective_n__", "eligible__") := NULL]
  x[]
}

allocate_injury_effective_n <- function(
    data,
    count_column,
    effective_total,
    output_column,
    strata = c("Death_Prov", "Sex", "Popgroup", "age5")) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(data))
  assert_has_columns(x, c(strata, "nbdcode", count_column), "injury effective-size allocation")

  effective_total <- suppressWarnings(as.numeric(effective_total))
  if (length(effective_total) != 1L || !is.finite(effective_total) || effective_total < 0) {
    stop("The injury survey effective sample size must be finite and non-negative.", call. = FALSE)
  }

  stratum <- x[, .(
    weighted_total__ = sum(as.numeric(get(count_column)), na.rm = TRUE)
  ), by = strata]
  grand_total <- sum(stratum$weighted_total__, na.rm = TRUE)
  if (nrow(stratum) == 0L) {
    x[, (output_column) := numeric()]
    return(x[])
  }
  if (grand_total > 0 && effective_total > 0) {
    stratum[, effective_n__ := effective_total * weighted_total__ / grand_total]
  } else {
    stratum[, effective_n__ := 0]
  }
  x <- merge(x, stratum[, c(strata, "effective_n__"), with = FALSE],
             by = strata, all.x = TRUE, sort = FALSE)
  x[, (output_column) := pmax(0, as.numeric(effective_n__))]
  x[, effective_n__ := NULL]
  x[]
}

# Survey-design injury evidence ------------------------------------------------
#
# Total injury completeness uses every injury record retained by the published
# IMS 2009 and cleaned FAMHIS 2017 criteria. Detailed cause fractions use only
# records with a directly specified mechanism on the common 15-cause list.
# Generic or unresolved injury records therefore inform the total envelope but
# cannot distort the cause composition. IMS and FAMHIS uncertainty is generated
# by resampling sampled mortuaries/forensic pathology services within their
# original sampling strata; the same replicate jointly determines the national
# level, demographic profile and specified cause counts.

injury_survey_text <- function(value) {
  out <- trimws(as.character(value))
  out[is.na(out)] <- ""
  out
}

injury_survey_psu_id <- function(value, prefix) {
  out <- injury_survey_text(value)
  missing <- !nzchar(out)
  if (any(missing)) {
    out[missing] <- paste0(prefix, "_missing_", which(missing))
  }
  out
}

injury_survey_stratum_id <- function(...) {
  values <- list(...)
  values <- lapply(values, function(value) {
    out <- injury_survey_text(value)
    out[!nzchar(out)] <- "<NA>"
    out
  })
  do.call(paste, c(values, list(sep = "|")))
}

injury_build_ims_design <- function(data) {
  require_package("data.table")
  x <- standardise_injury_columns(data, list(
    weight = c("Weight", "wht"),
    province = c("Province", "prov"),
    Cause_of_death = c("causeofdeath", "cause_type"),
    age_raw = c("nbd_age", "age5"),
    nbdgr = c("NBDgr", "nbd_group"),
    Population_group = c("populationgroup", "popgroup"),
    Sex = c("sex", "gender"),
    psu_raw = c("Mortuary_code", "mortuary_code", "fps_code"),
    size_raw = c("size", "mortuary_size"),
    type_raw = c("type", "metro_type")
  ))
  numeric_columns <- c(
    "weight", "province", "Cause_of_death", "age_raw", "nbdgr",
    "Population_group", "Sex"
  )
  for (column in numeric_columns) {
    x[, (column) := suppressWarnings(as.numeric(get(column)))]
  }
  x[!is.finite(weight) | weight < 0, weight := 0]

  # Published IMS injury level: definite injuries only, using the supplied
  # survey weight. Post-publication NBD substitutions and half-undetermined
  # additions are deliberately excluded from this published-compatible anchor.
  x[, level_eligible := is.finite(Cause_of_death) & Cause_of_death == 1]
  x[, nbdcode := as.integer(
    INJURY_NBD_GROUP_MAP[as.character(as.integer(nbdgr))]
  )]
  x[, cause_eligible := level_eligible & nbdcode %in% INJURY_CODES]

  x[, Death_Prov := as.integer(
    PROVINCE_FROM_IMS[as.character(as.integer(province))]
  )]
  x[is.na(Death_Prov) | !Death_Prov %in% 1:9, Death_Prov := 10L]
  x[, Popgroup := as.integer(
    POP_GROUP_FROM_IMS[as.character(as.integer(Population_group))]
  )]
  x[is.na(Popgroup) | !Popgroup %in% 1:4, Popgroup := 5L]
  x[is.na(Sex) | !Sex %in% 1:2, Sex := 3L]
  x[, age5 := as.integer(age_raw) + 1L]
  x[!is.finite(age5) | !age5 %in% 2:20, age5 := 21L]
  x[, psu_id := injury_survey_psu_id(psu_raw, "IMS")]
  x[, stratum_id := injury_survey_stratum_id(province, size_raw, type_raw)]

  level_records <- x[level_eligible == TRUE & weight > 0]
  cause_records <- x[cause_eligible == TRUE & weight > 0]
  if (!nrow(level_records) || !nrow(cause_records)) {
    stop("IMS has no usable published-eligible injury records.", call. = FALSE)
  }

  level_domain <- level_records[, .(
    weighted_injuries = sum(weight, na.rm = TRUE)
  ), by = .(stratum_id, psu_id, Death_Prov, Sex, age5)]
  cause_domain <- cause_records[, .(
    weighted_causes = sum(weight, na.rm = TRUE)
  ), by = .(
    stratum_id, psu_id, Death_Prov, Sex, Popgroup, age5, nbdcode
  )]
  psus <- unique(level_records[, .(stratum_id, psu_id)])
  assert_unique_key(psus, c("stratum_id", "psu_id"), "IMS survey PSUs")

  list(
    survey = "IMS 2009",
    survey_year = 2009L,
    level_definition = "Cause_of_death == 1 using the supplied survey weight",
    cause_definition = paste(
      "Cause_of_death == 1 and nbdgr 1-16; G-coded/unresolved injuries",
      "excluded from the cause-fraction denominator"
    ),
    psus = psus,
    level_domain = level_domain,
    cause_domain = cause_domain,
    level_effective_n = kish_effective_sample_size(level_records$weight),
    cause_effective_n = kish_effective_sample_size(cause_records$weight),
    unweighted_level_records = nrow(level_records),
    unweighted_cause_records = nrow(cause_records),
    weighted_level_total = sum(level_records$weight),
    weighted_cause_total = sum(cause_records$weight),
    external_reference = data.table::data.table(
      survey = "IMS 2009",
      survey_year = 2009L,
      reference_version = "Peer-reviewed IMS estimate",
      reference_estimate = 52493,
      reference_lower = 46930,
      reference_upper = 58057
    )
  )
}

injury_build_famhis_design <- function(data) {
  require_package("data.table")
  x <- standardise_injury_columns(data, list(
    mechanism_raw = c("nbd_cod_mech", "nbdcodmech", "mechanism"),
    non_nat_undert = c("non_nat_undert", "nonnatundert"),
    weight = c("wht", "weight"),
    Death_Prov = c("prov", "province"),
    Sex_raw = c("gender_b", "sex", "gender"),
    Population_group = c("ethnicity_b", "popgroup", "population_group"),
    age_value = c("age_Non_Natural", "agenonnatural", "age"),
    age_unit = c("age_unitss_Non_Natural", "ageunitsnonnatural", "age_unit"),
    psu_raw = c("fps_code_updated", "fps_code", "mortuary_code"),
    stratum_raw = c("stratprov", "stratum")
  ))
  for (column in c(
    "non_nat_undert", "weight", "Death_Prov", "Sex_raw",
    "Population_group", "age_value", "age_unit"
  )) {
    x[, (column) := suppressWarnings(as.numeric(get(column)))]
  }
  x[!is.finite(weight) | weight < 0, weight := 0]
  x[, mechanism_raw := injury_survey_text(mechanism_raw)]

  # Later cleaned FAMHIS publication criterion: an injury mechanism is present
  # and the record is not explicitly flagged as non-injury by
  # non_nat_undert == 0. This reproduces 29,944 weighted records and the later
  # published national estimate directly from the supplied data.
  x[, level_eligible := nzchar(mechanism_raw) &
      (is.na(non_nat_undert) | non_nat_undert != 0)]
  x[, mechanism_clean := toupper(gsub("\\.", "", mechanism_raw))]
  mechanism_map <- c(FAMHIS_MECHANISM_MAP, ZA140 = 141L)
  x[, nbdcode := as.integer(mechanism_map[mechanism_clean])]
  x[, cause_eligible := level_eligible & nbdcode %in% INJURY_CODES]

  x[, Sex := as.integer(Sex_raw + 1L)]
  x[is.na(Sex) | !Sex %in% 1:2, Sex := 3L]
  x[, Popgroup := as.integer(
    POP_GROUP_FROM_IMS[as.character(as.integer(Population_group))]
  )]
  x[is.na(Popgroup) | !Popgroup %in% 1:4, Popgroup := 5L]
  x[, age5 := age5_from_famhis(age_value, age_unit)]
  x[is.na(age5) | !age5 %in% 1:20, age5 := 21L]
  x[is.na(Death_Prov) | !Death_Prov %in% 1:9, Death_Prov := 10L]
  x[, psu_id := injury_survey_psu_id(psu_raw, "FAMHIS")]
  x[, stratum_id := injury_survey_text(stratum_raw)]
  x[!nzchar(stratum_id), stratum_id := paste0("province_", Death_Prov)]

  level_records <- x[level_eligible == TRUE & weight > 0]
  cause_records <- x[cause_eligible == TRUE & weight > 0]
  if (!nrow(level_records) || !nrow(cause_records)) {
    stop("FAMHIS has no usable published-eligible injury records.", call. = FALSE)
  }

  level_domain <- level_records[, .(
    weighted_injuries = sum(weight, na.rm = TRUE)
  ), by = .(stratum_id, psu_id, Death_Prov, Sex, age5)]
  cause_domain <- cause_records[, .(
    weighted_causes = sum(weight, na.rm = TRUE)
  ), by = .(
    stratum_id, psu_id, Death_Prov, Sex, Popgroup, age5, nbdcode
  )]
  psus <- unique(level_records[, .(stratum_id, psu_id)])
  assert_unique_key(psus, c("stratum_id", "psu_id"), "FAMHIS survey PSUs")

  list(
    survey = "FAMHIS 2017",
    survey_year = 2017L,
    level_definition = paste(
      "Nonblank nbd_cod_mech and not explicitly excluded by",
      "non_nat_undert == 0"
    ),
    cause_definition = paste(
      "Published-eligible records with a direct common 15-cause mechanism;",
      "unknown/generic mechanisms excluded from the cause-fraction denominator"
    ),
    psus = psus,
    level_domain = level_domain,
    cause_domain = cause_domain,
    level_effective_n = kish_effective_sample_size(level_records$weight),
    cause_effective_n = kish_effective_sample_size(cause_records$weight),
    unweighted_level_records = nrow(level_records),
    unweighted_cause_records = nrow(cause_records),
    weighted_level_total = sum(level_records$weight),
    weighted_cause_total = sum(cause_records$weight),
    external_reference = data.table::rbindlist(list(
      data.table::data.table(
        survey = "FAMHIS 2017",
        survey_year = 2017L,
        reference_version = "Later cleaned peer-reviewed estimate",
        reference_estimate = 53288,
        reference_lower = 49964,
        reference_upper = 56613
      ),
      data.table::data.table(
        survey = "FAMHIS 2017",
        survey_year = 2017L,
        reference_version = "Original 2021 report",
        reference_estimate = 54734,
        reference_lower = 51376,
        reference_upper = 58093
      )
    ))
  )
}

injury_bootstrap_psu_multipliers <- function(psus, stochastic = FALSE) {
  require_package("data.table")
  x <- data.table::as.data.table(data.table::copy(psus))
  assert_unique_key(x, c("stratum_id", "psu_id"), "injury survey PSUs")
  if (!isTRUE(stochastic)) {
    x[, multiplier := 1L]
    return(x[])
  }
  out <- x[, {
    n_psu <- .N
    if (n_psu <= 1L) {
      .(psu_id = psu_id, multiplier = 1L)
    } else {
      selected <- sample.int(n_psu, n_psu, replace = TRUE)
      .(psu_id = psu_id, multiplier = tabulate(selected, nbins = n_psu))
    }
  }, by = stratum_id]
  out[]
}

injury_weighted_domain_from_psu <- function(domain, multipliers, value_column) {
  require_package("data.table")
  x <- merge(
    data.table::as.data.table(data.table::copy(domain)),
    data.table::as.data.table(data.table::copy(multipliers)),
    by = c("stratum_id", "psu_id"),
    all.x = TRUE,
    sort = FALSE
  )
  x[is.na(multiplier), multiplier := 0]
  x[, (value_column) := as.numeric(get(value_column)) * multiplier]
  x[]
}

injury_envelope_table_from_design <- function(design, multipliers = NULL) {
  require_package("data.table")
  if (is.null(multipliers)) {
    multipliers <- injury_bootstrap_psu_multipliers(
      design$psus,
      stochastic = FALSE
    )
  }
  x <- injury_weighted_domain_from_psu(
    design$level_domain,
    multipliers,
    "weighted_injuries"
  )
  level_total <- sum(x$weighted_injuries, na.rm = TRUE)
  x <- x[, .(
    survey_injury_total = sum(weighted_injuries, na.rm = TRUE)
  ), by = .(Death_Prov, Sex, age5)]
  x <- redistribute_unknown(
    x, "Sex", "survey_injury_total",
    by = c("Death_Prov", "age5"),
    unknown = 3L, targets = 1:2
  )
  x <- redistribute_unknown(
    x, "age5", "survey_injury_total",
    by = c("Death_Prov", "Sex"),
    unknown = 21L, targets = 1:20
  )
  x <- redistribute_unknown(
    x, "Death_Prov", "survey_injury_total",
    by = c("Sex", "age5"),
    unknown = 10L, targets = 1:9
  )
  x <- complete_cells(
    x,
    dimensions = c("Death_Prov", "Sex", "age5"),
    values = "survey_injury_total",
    levels = list(Death_Prov = 1:9, Sex = 1:2, age5 = 1:20)
  )
  x[, survey_total := survey_injury_total]
  x <- allocate_injury_envelope_effective_n(
    x,
    count_column = "survey_injury_total",
    effective_total = design$level_effective_n,
    output_column = "survey_effective_n"
  )
  x[, `:=`(
    survey_injury_share = safe_ratio(
      survey_injury_total,
      sum(survey_injury_total),
      zero = 0
    ),
    survey_year = as.integer(design$survey_year),
    survey = as.character(design$survey),
    survey_level_estimate = level_total,
    survey_level_record_total = level_total,
    survey_level_source = paste0(
      "Calculated from supplied microdata using: ",
      design$level_definition
    ),
    envelope_definition = design$level_definition
  )]
  data.table::setorder(x, Death_Prov, Sex, age5)
  x[]
}

injury_cause_table_from_design <- function(design, multipliers = NULL) {
  require_package("data.table")
  if (is.null(multipliers)) {
    multipliers <- injury_bootstrap_psu_multipliers(
      design$psus,
      stochastic = FALSE
    )
  }
  x <- injury_weighted_domain_from_psu(
    design$cause_domain,
    multipliers,
    "weighted_causes"
  )
  x <- x[, .(
    survey_count = sum(weighted_causes, na.rm = TRUE)
  ), by = .(Death_Prov, Sex, Popgroup, age5, nbdcode)]
  x <- redistribute_unknown(
    x, "Sex", "survey_count",
    by = c("Popgroup", "Death_Prov", "age5", "nbdcode"),
    unknown = 3L, targets = 1:2
  )
  x <- redistribute_unknown(
    x, "age5", "survey_count",
    by = c("Popgroup", "Death_Prov", "Sex", "nbdcode"),
    unknown = 21L, targets = 1:20
  )
  x <- redistribute_unknown(
    x, "Popgroup", "survey_count",
    by = c("age5", "Death_Prov", "Sex", "nbdcode"),
    unknown = 5L, targets = 1:4
  )
  x <- redistribute_unknown(
    x, "Death_Prov", "survey_count",
    by = c("age5", "Sex", "Popgroup", "nbdcode"),
    unknown = 10L, targets = 1:9
  )
  x <- complete_cells(
    x,
    dimensions = c(
      "Death_Prov", "Sex", "Popgroup", "age5", "nbdcode"
    ),
    values = "survey_count",
    levels = list(
      Death_Prov = 1:9,
      Sex = 1:2,
      Popgroup = 1:4,
      age5 = 1:20,
      nbdcode = INJURY_CODES
    )
  )
  if (as.integer(design$survey_year) == 2009L) {
    # IMS supplies an all-infant profile. As in the historical NBD program,
    # copy the post-neonatal composition to the neonatal row. This affects only
    # cause fractions; it does not enter the survey injury-level total.
    x <- x[age5 != 1L]
    neonatal <- data.table::copy(x[age5 == 2L])
    neonatal[, age5 := 1L]
    x <- data.table::rbindlist(list(x, neonatal), use.names = TRUE)
  }
  effective_total <- design$cause_effective_n
  x <- allocate_injury_effective_n(
    x,
    count_column = "survey_count",
    effective_total = effective_total,
    output_column = "survey_effective_n"
  )
  count_name <- paste0("Inj", design$survey_year)
  effn_name <- paste0("EffN", design$survey_year)
  data.table::setnames(
    x,
    c("survey_count", "survey_effective_n"),
    c(count_name, effn_name)
  )
  data.table::setorder(x, Death_Prov, Sex, Popgroup, age5, nbdcode)
  x[]
}

injury_survey_design_draw <- function(artifact, seed, stochastic = TRUE) {
  require_package("data.table")
  if (!is.list(artifact) || is.null(artifact$ims) || is.null(artifact$famhis)) {
    stop("The injury survey-design artifact is incomplete.", call. = FALSE)
  }
  set.seed(as.integer(seed))
  ims_multipliers <- injury_bootstrap_psu_multipliers(
    artifact$ims$psus,
    stochastic = stochastic
  )
  famhis_multipliers <- injury_bootstrap_psu_multipliers(
    artifact$famhis$psus,
    stochastic = stochastic
  )
  ims_envelope <- injury_envelope_table_from_design(
    artifact$ims,
    ims_multipliers
  )
  famhis_envelope <- injury_envelope_table_from_design(
    artifact$famhis,
    famhis_multipliers
  )
  ims_causes <- injury_cause_table_from_design(
    artifact$ims,
    ims_multipliers
  )
  famhis_causes <- injury_cause_table_from_design(
    artifact$famhis,
    famhis_multipliers
  )
  cause_key <- c("Death_Prov", "Sex", "Popgroup", "age5", "nbdcode")
  causes <- merge(
    ims_causes,
    famhis_causes,
    by = cause_key,
    all = TRUE,
    sort = FALSE
  )
  for (column in c("Inj2009", "Inj2017", "EffN2009", "EffN2017")) {
    causes[is.na(get(column)), (column) := 0]
  }
  if (isTRUE(stochastic)) {
    # The PSU bootstrap itself supplies IMS/FAMHIS sampling uncertainty. Do not
    # add a second Dirichlet layer to these two survey compositions.
    causes[, `:=`(EffN2009 = 0, EffN2017 = 0)]
  }
  list(
    envelope_surveys = data.table::rbindlist(
      list(ims_envelope, famhis_envelope),
      use.names = TRUE,
      fill = TRUE
    ),
    cause_surveys = causes[],
    diagnostics = data.table::data.table(
      survey = c("IMS 2009", "FAMHIS 2017"),
      survey_year = c(2009L, 2017L),
      level_total = c(
        unique(ims_envelope$survey_level_estimate),
        unique(famhis_envelope$survey_level_estimate)
      ),
      sampled_psu_slots = c(
        sum(ims_multipliers$multiplier),
        sum(famhis_multipliers$multiplier)
      ),
      distinct_selected_psus = c(
        ims_multipliers[multiplier > 0, .N],
        famhis_multipliers[multiplier > 0, .N]
      )
    )
  )
}

prepare_injury_survey_bundle <- function(cfg) {
  require_package("data.table")
  ims_raw <- read_tabular(raw_file(cfg, "ims_2009", must_exist = TRUE))
  famhis_raw <- read_tabular(raw_file(cfg, "famhis_2017", must_exist = TRUE))
  design <- list(
    version = "stratified-psu-bootstrap-v1",
    ims = injury_build_ims_design(ims_raw),
    famhis = injury_build_famhis_design(famhis_raw),
    bootstrap_method = paste(
      "Sample sampled PSUs with replacement within original strata;",
      "singleton sampled strata held fixed"
    )
  )
  point <- injury_survey_design_draw(
    design,
    seed = 1L,
    stochastic = FALSE
  )

  nims_path <- raw_file(cfg, "nims_2000", must_exist = TRUE)
  nims_extension <- tolower(tools::file_ext(nims_path))
  nims_input <- if (nims_extension %in% c("xls", "xlsx")) {
    read_tabular(
      nims_path,
      sheet = cfg$settings$injury_nims_sheet %||% 1,
      .name_repair = "unique_quiet"
    )
  } else {
    read_tabular(nims_path)
  }
  nims_national <- prepare_nims_2000(
    nims_input,
    count_floor = as.numeric(
      cfg$settings$injury_nims_count_floor %||% 1e-6
    )
  )
  nims <- expand_nims_2000_with_ims(
    nims_national,
    point$cause_surveys[, .(
      Death_Prov, Sex, Popgroup, age5, nbdcode, Inj2009, EffN2009
    )]
  )

  cause_key <- c("Death_Prov", "Sex", "Popgroup", "age5", "nbdcode")
  surveys <- merge(
    nims,
    point$cause_surveys,
    by = cause_key,
    all = TRUE,
    sort = FALSE
  )
  for (column in c("Inj2000", "Inj2009", "Inj2017")) {
    surveys[is.na(get(column)), (column) := 0]
  }
  for (column in c("EffN2000", "EffN2009", "EffN2017")) {
    surveys[
      is.na(get(column)) | !is.finite(get(column)) | get(column) < 0,
      (column) := 0
    ]
  }
  surveys[is.na(nims_source_zero), nims_source_zero := TRUE]
  surveys[is.na(nims_spatial_share), nims_spatial_share := 1 / 36]
  surveys[is.na(nims_spatial_status),
    nims_spatial_status := "Equal 1/36 fallback"]
  data.table::setorderv(surveys, cause_key)
  assert_unique_key(
    surveys,
    cause_key,
    "harmonised NIMS-IMS-FAMHIS injury surveys"
  )

  reference <- data.table::rbindlist(list(
    design$ims$external_reference,
    design$famhis$external_reference
  ), use.names = TRUE, fill = TRUE)
  empirical <- data.table::data.table(
    survey = c("IMS 2009", "FAMHIS 2017"),
    survey_year = c(2009L, 2017L),
    empirical_level_estimate = c(
      design$ims$weighted_level_total,
      design$famhis$weighted_level_total
    ),
    unweighted_level_records = c(
      design$ims$unweighted_level_records,
      design$famhis$unweighted_level_records
    ),
    empirical_well_specified_cause_mass = c(
      design$ims$weighted_cause_total,
      design$famhis$weighted_cause_total
    ),
    well_specified_share = c(
      design$ims$weighted_cause_total / design$ims$weighted_level_total,
      design$famhis$weighted_cause_total / design$famhis$weighted_level_total
    ),
    level_definition = c(
      design$ims$level_definition,
      design$famhis$level_definition
    ),
    cause_definition = c(
      design$ims$cause_definition,
      design$famhis$cause_definition
    )
  )
  audit <- merge(reference, empirical, by = c("survey", "survey_year"),
                 all.x = TRUE, sort = FALSE)
  audit[, `:=`(
    difference = empirical_level_estimate - reference_estimate,
    relative_difference = safe_ratio(
      empirical_level_estimate - reference_estimate,
      reference_estimate,
      zero = NA_real_
    )
  )]
  design$point_cause_surveys <- surveys
  design$point_envelope_surveys <- point$envelope_surveys
  design$point_audit <- audit

  list(
    cause_surveys = surveys[],
    envelope_surveys = point$envelope_surveys[],
    design_artifact = design,
    audit = audit[]
  )
}

injury_survey_bootstrap_audit <- function(artifact, cfg = NULL) {
  require_package("data.table")
  if (!is.list(artifact) || is.null(artifact$ims) || is.null(artifact$famhis)) {
    stop("The injury survey-design artifact is incomplete.", call. = FALSE)
  }
  settings <- injury_bootstrap_settings(cfg)
  surveys <- list(artifact$ims, artifact$famhis)
  national <- list()
  province <- list()
  cause <- list()

  for (index in seq_along(surveys)) {
    design <- surveys[[index]]
    total_boot <- injury_psu_bootstrap_total(
      design$level_domain,
      stratum = "stratum_id",
      psu = "psu_id",
      weight = "weighted_injuries",
      n_replicates = settings$n_replicates,
      seed = settings$seed + 100L * index + 1L
    )
    province_boot <- injury_psu_bootstrap_composition(
      design$level_domain,
      stratum = "stratum_id",
      psu = "psu_id",
      category = "Death_Prov",
      weight = "weighted_injuries",
      levels = 1:9,
      n_replicates = settings$n_replicates,
      seed = settings$seed + 100L * index + 2L
    )
    cause_boot <- injury_psu_bootstrap_composition(
      design$cause_domain,
      stratum = "stratum_id",
      psu = "psu_id",
      category = "nbdcode",
      weight = "weighted_causes",
      levels = INJURY_CODES,
      n_replicates = settings$n_replicates,
      seed = settings$seed + 100L * index + 3L
    )

    total_summary <- injury_bootstrap_level_summary(
      total_boot$point,
      total_boot$replicates
    )
    national[[index]] <- data.table::data.table(
      survey = design$survey,
      survey_year = as.integer(design$survey_year),
      estimate = as.numeric(total_boot$point),
      standard_error = total_summary$standard_error,
      lower = total_summary$lower,
      upper = total_summary$upper,
      bootstrap_replicates = total_summary$n_replicates,
      unweighted_records = as.integer(design$unweighted_level_records),
      weighted_well_specified_causes = as.numeric(design$weighted_cause_total),
      well_specified_share = as.numeric(
        design$weighted_cause_total / design$weighted_level_total
      ),
      level_definition = design$level_definition,
      variance_method = paste(
        "Stratified PSU bootstrap; sampled PSUs resampled within strata;",
        "singleton sampled strata fixed"
      )
    )

    for (j in seq_along(province_boot$point)) {
      values <- province_boot$replicates[, j]
      province[[length(province) + 1L]] <- data.table::data.table(
        survey = design$survey,
        survey_year = as.integer(design$survey_year),
        Death_Prov = as.integer(names(province_boot$point)[[j]]),
        estimate = as.numeric(province_boot$point[[j]]),
        standard_error = stats::sd(values),
        lower = as.numeric(stats::quantile(
          values, 0.025, names = FALSE, type = 8
        )),
        upper = as.numeric(stats::quantile(
          values, 0.975, names = FALSE, type = 8
        ))
      )
    }

    point_total <- sum(cause_boot$point)
    replicate_total <- rowSums(cause_boot$replicates)
    valid <- is.finite(replicate_total) & replicate_total > 0
    fractions <- cause_boot$replicates[valid, , drop = FALSE] /
      replicate_total[valid]
    for (j in seq_along(cause_boot$point)) {
      values <- fractions[, j]
      cause[[length(cause) + 1L]] <- data.table::data.table(
        survey = design$survey,
        survey_year = as.integer(design$survey_year),
        nbdcode = as.integer(names(cause_boot$point)[[j]]),
        fraction = as.numeric(cause_boot$point[[j]] / point_total),
        standard_error = stats::sd(values),
        lower = as.numeric(stats::quantile(
          values, 0.025, names = FALSE, type = 8
        )),
        upper = as.numeric(stats::quantile(
          values, 0.975, names = FALSE, type = 8
        )),
        cause_definition = design$cause_definition
      )
    }
  }

  list(
    national = data.table::rbindlist(national, use.names = TRUE, fill = TRUE),
    province = data.table::rbindlist(province, use.names = TRUE, fill = TRUE),
    cause = data.table::rbindlist(cause, use.names = TRUE, fill = TRUE)
  )
}


